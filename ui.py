def retheme_all_widgets(old: dict[str, str], new: dict[str, str]) -> None:
    """
    CANLI tam tema değişimi. Uygulamadaki HER widget'ın stylesheet'inde eski
    palet renklerini yenileriyle değiştirir ve yeniden çizdirir. Böylece renk
    değişimi yalnızca boyanan öğelerde değil, panel/buton/kenarlık dahil tüm
    arayüzde ANINDA uygulanır — yeniden başlatma gerekmez.
    """
    mapping = {old[k].lower(): new[k].lower()
               for k in old if old[k].lower() != new.get(k, old[k]).lower()}
    if not mapping:
        return
    app = QApplication.instance()
    if app is None:
        return
    for w in app.allWidgets():
        try:
            ss = w.styleSheet()
            if ss:
                s2 = ss
                for o, n in mapping.items():
                    if o in s2:
                        s2 = s2.replace(o, n)
                if s2 != ss:
                    w.setStyleSheet(s2)
            w.update()
        except Exception:
            pass


def qcol(h: str, a: int = 255) -> QColor:
    c = QColor(h); c.setAlpha(a); return c


class _Backend(QObject):
    """Ponte JS<->Python exposta como 'backend' no QWebChannel."""

    def __init__(self, main_window):
        super().__init__()
        self._win = main_window

    @pyqtSlot(str)
    def on_text_command(self, text: str):
        if self._win.on_text_command:
            threading.Thread(
                target=self._win.on_text_command, args=(text,), daemon=True
            ).start()

    @pyqtSlot()
    def request_interrupt(self):
        if self._win.on_interrupt:
            self._win.on_interrupt()

    @pyqtSlot()
    def request_toggle_mute(self):
        self._win._toggle_mute()

    @pyqtSlot()
    def request_file_dialog(self):
        path, _ = QFileDialog.getOpenFileName(
            self._win, "Selecionar arquivo", "",
            "Todos os arquivos (*.*)"
        )
        if not path:
            return
        self._win._current_file = path
        filename = Path(path).name
        safe_name = json.dumps(filename)
        self._win.webview.page().runJavaScript(
            f"window.jarvisFileSelected({safe_name});"
        )

