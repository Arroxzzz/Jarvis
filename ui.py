    def _start_global_hotkey(self) -> None:
        """F4 global — funciona mesmo com JARVIS sem foco (jogos fullscreen)."""
        try:
            from pynput import keyboard as _pynput_kb
        except ImportError:
            print("[Hotkey] pynput não instalado — F4 global desativado.")
            return

        def _on_f4():
            self._mute_hotkey_sig.emit()

        def _on_emergency():
            self._emergency_stop()

        def _run():
            with _pynput_kb.GlobalHotKeys({
                '<f4>': _on_f4,
                '<ctrl>+<shift>+<f12>': _on_emergency,
            }) as listener:
                listener.join()

        threading.Thread(target=_run, daemon=True, name="GlobalHotkeyF4").start()

